using System.Text;

namespace DbmlToSql;

/// <summary>
/// Генерирует PostgreSQL DDL из разобранной DBML-модели.
/// </summary>
public sealed class SqlGenerator
{
    private readonly DbmlParser _model;

    public SqlGenerator(DbmlParser model)
    {
        _model = model;
    }

    public string GenerateSchema()
    {
        var sb = new StringBuilder();

        sb.AppendLine("-- ============================================================");
        sb.AppendLine($"-- {(_model.ProjectName ?? "database")} — схема таблиц");
        sb.AppendLine("-- Сгенерировано автоматически из docs/dbml/schema.dbml");
        sb.AppendLine("-- Команда: dotnet run --project tools/DbmlToSql");
        sb.AppendLine("-- ============================================================");
        sb.AppendLine();
        sb.AppendLine("BEGIN;");
        sb.AppendLine();

        foreach (var table in _model.Tables)
        {
            sb.AppendLine($"-- {table.Name}");
            if (!string.IsNullOrWhiteSpace(table.Note))
            {
                sb.AppendLine($"-- {table.Note}");
            }
            sb.AppendLine($"CREATE TABLE IF NOT EXISTS {Quote(table.Name)} (");

            var definitions = new List<string>();

            // Составной первичный ключ (несколько колонок с primary key)
            var pkColumns = table.Columns.Where(c => c.PrimaryKey).ToList();
            var hasSinglePk = pkColumns.Count == 1;
            var hasCompositePk = pkColumns.Count > 1;

            foreach (var col in table.Columns)
            {
                var sbCol = new StringBuilder();
                sbCol.Append($"  {Quote(col.Name)} {MapType(col)}");

                if (hasSinglePk && col.PrimaryKey)
                {
                    // IDENTITY-колонка должна также быть PRIMARY KEY
                    sbCol.Append(col.Increment
                        ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
                        : " PRIMARY KEY");
                }
                else if (hasCompositePk && col.PrimaryKey)
                {
                    // составной PK добавляется отдельным CONSTRAINT в конце таблицы
                    sbCol.Append(" NOT NULL");
                }

                if (col.NotNull && !(hasSinglePk && col.PrimaryKey))
                {
                    sbCol.Append(" NOT NULL");
                }

                if (col.Unique && !(hasSinglePk && col.PrimaryKey))
                {
                    sbCol.Append(" UNIQUE");
                }

                if (!string.IsNullOrWhiteSpace(col.Default))
                {
                    sbCol.Append($" DEFAULT {col.Default}");
                }

                definitions.Add(sbCol.ToString());
            }

            // Составной первичный ключ
            if (pkColumns.Count > 1)
            {
                var names = string.Join(", ", pkColumns.Select(c => Quote(c.Name)));
                definitions.Add($"  PRIMARY KEY ({names})");
            }

            // Комментарии к колонкам выносим на отдельные строки,
            // иначе «--» съедает запятую-разделитель списка колонок.
            var lines = new List<string>();
            var colDefs = table.Columns
                .Select(c => definitions.FirstOrDefault(d => d.StartsWith($"  {Quote(c.Name)} ", StringComparison.Ordinal)))
                .Where(d => d != null)
                .Select(d => d!)
                .ToList();

            for (var i = 0; i < table.Columns.Count; i++)
            {
                var col = table.Columns[i];
                var definition = colDefs[i];

                // Последняя колонка без составного PK не получает запятую
                var isLast = i == table.Columns.Count - 1 && pkColumns.Count <= 1;
                lines.Add(isLast ? definition : definition + ",");

                if (!string.IsNullOrWhiteSpace(col.Note))
                {
                    lines.Add($"    -- {col.Note}");
                }
            }

            if (pkColumns.Count > 1)
            {
                lines.Add($"  PRIMARY KEY ({string.Join(", ", pkColumns.Select(c => Quote(c.Name)))})");
            }

            sb.AppendLine(string.Join("\n", lines));
            sb.AppendLine(");");
            sb.AppendLine();
        }

        sb.AppendLine("COMMIT;");
        return sb.ToString();
    }

    /// <summary>Создаёт ALTER TABLE с внешними ключами (Ref).</summary>
    public string GenerateConstraints()
    {
        var sb = new StringBuilder();

        sb.AppendLine("-- ============================================================");
        sb.AppendLine("-- Внешние ключи (Ref)");
        sb.AppendLine("-- Сгенерировано автоматически из docs/dbml/schema.dbml");
        sb.AppendLine("-- ============================================================");
        sb.AppendLine();
        sb.AppendLine("BEGIN;");
        sb.AppendLine();

        var counter = 0;
        foreach (var r in _model.Refs)
        {
            var table = _model.Tables.FirstOrDefault(t => t.Name == r.TableName);
            if (table is null)
            {
                continue;
            }

            var column = table.Columns.FirstOrDefault(c => c.Name == r.ColumnName);
            if (column is null)
            {
                Console.Error.WriteLine($"  ! Пропущен Ref: колонка {r.TableName}.{r.ColumnName} не найдена");
                continue;
            }

            var constraintName = $"fk_{r.TableName}_{r.ColumnName}";
            counter++;

            sb.Append($"ALTER TABLE {Quote(r.TableName)} ");
            sb.AppendLine($"ADD CONSTRAINT {Quote(constraintName)}");
            sb.AppendLine($"    FOREIGN KEY ({Quote(r.ColumnName)})");
            sb.AppendLine($"    REFERENCES {Quote(r.RefTableName)} ({Quote(r.RefColumnName)})");

            if (!string.IsNullOrWhiteSpace(r.OnDelete) && r.OnDelete != "no action")
            {
                sb.AppendLine($"    ON DELETE {r.OnDelete.ToUpperInvariant()}");
            }

            if (!string.IsNullOrWhiteSpace(r.OnUpdate) && r.OnUpdate != "no action")
            {
                sb.AppendLine($"    ON UPDATE {r.OnUpdate.ToUpperInvariant()}");
            }

            sb.AppendLine(";");
            sb.AppendLine();
        }

        sb.AppendLine("COMMIT;");
        return sb.ToString();
    }

    /// <summary>Создаёт индексы (включая уникальные, создаваемые по Unique).</summary>
    public string GenerateIndexes()
    {
        var sb = new StringBuilder();

        sb.AppendLine("-- ============================================================");
        sb.AppendLine("-- Индексы");
        sb.AppendLine("-- Сгенерировано автоматически из docs/dbml/schema.dbml");
        sb.AppendLine("-- ============================================================");
        sb.AppendLine();
        sb.AppendLine("BEGIN;");
        sb.AppendLine();

        foreach (var index in _model.Indexes)
        {
            var cols = string.Join(", ", index.Columns.Select(Quote));
            var unique = index.Unique ? "UNIQUE " : string.Empty;
            sb.AppendLine($"CREATE {unique}INDEX IF NOT EXISTS {Quote(index.Name)}");
            sb.AppendLine($"    ON {Quote(index.TableName)} ({cols});");
            sb.AppendLine();
        }

        // Уникальные колонки автоматически получают индекс в PostgreSQL,
        // но составные PK — тоже. Дополнительные индексы для поиска.
        var searchIndexes = new (string Table, string[] Columns, string Name)[]
        {
            ("cards", new[] { "title" }, "idx_cards_title"),
            ("cards", new[] { "set_id" }, "idx_cards_set_id"),
            ("cards", new[] { "rarity_id" }, "idx_cards_rarity_id"),
            ("cards", new[] { "type_id" }, "idx_cards_type_id"),
            ("cards", new[] { "cost" }, "idx_cards_cost"),
            ("cards", new[] { "card_number" }, "idx_cards_card_number"),
            ("card_aspects", new[] { "aspect_id" }, "idx_card_aspects_aspect_id"),
            ("card_traits", new[] { "trait_id" }, "idx_card_traits_trait_id"),
            ("comments", new[] { "card_id" }, "idx_comments_card_id"),
        };

        foreach (var (table, columns, name) in searchIndexes)
        {
            if (!_model.Tables.Any(t => t.Name == table))
            {
                continue;
            }

            var cols = string.Join(", ", columns.Select(Quote));
            sb.AppendLine($"CREATE INDEX IF NOT EXISTS {Quote(name)}");
            sb.AppendLine($"    ON {Quote(table)} ({cols});");
            sb.AppendLine();
        }

        sb.AppendLine("COMMIT;");
        return sb.ToString();
    }

    private static string Quote(string identifier)
    {
        return "\"" + identifier.Replace("\"", "\"\"") + "\"";
    }

    /// <summary>Маппит типы DBML в типы PostgreSQL.</summary>
    private static string MapType(DbmlColumn col)
    {
        var type = col.Type.ToLowerInvariant();

        if (col.Increment)
        {
            return "integer";
        }

        return type switch
        {
            "int" => "integer",
            "integer" => "integer",
            "bigint" => "bigint",
            "smallint" => "smallint",
            "serial" => "serial",
            "bigserial" => "bigserial",
            "bool" => "boolean",
            "boolean" => "boolean",
            "text" => "text",
            "varchar" => "varchar(255)",
            "character varying" => "varchar(255)",
            "char" => "char(1)",
            "date" => "date",
            "time" => "time",
            "timestamp" => "timestamp",
            "timestamptz" => "timestamptz",
            "decimal" => "decimal(18,2)",
            "numeric" => "numeric(18,2)",
            "float" => "real",
            "double" => "double precision",
            "json" => "jsonb",
            "uuid" => "uuid",
            _ => type
        };
    }
}
